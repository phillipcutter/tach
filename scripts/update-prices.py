#!/usr/bin/env python3
"""Regenerates app/Sources/TachCore/PriceData.swift from LiteLLM's public price table
(https://github.com/BerriAI/litellm, MIT). Run it when a new model appears as "unpriced".

    scripts/update-prices.py [path/to/model_prices_and_context_window.json]

Without an argument the table is downloaded. Prices are US dollars per million tokens."""
import json, os, re, sys, urllib.request

URL = "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json"
EFFORTS = {"minimal", "low", "medium", "high", "xhigh", "max"}
# When several providers list the same model, the model maker's own entry wins.
FIRST_PARTY = ["", "anthropic", "openai", "gemini", "deepseek", "moonshot", "xai", "mistral", "xiaomi_mimo"]


def normalize(raw):
    """Must match ModelCatalog.normalize in Catalog.swift."""
    s = raw.lower().strip().rsplit("/", 1)[-1].split("[", 1)[0]
    parts = s.split("-")
    if len(parts[-1]) == 8 and parts[-1].isdigit():
        parts.pop()
    for suffix in (EFFORTS, {"tiered"}, {"thinking"}):
        if len(parts) > 2 and parts[-1] in suffix:
            parts.pop()
    return "-".join(parts)


def rank(key):
    prefix = key.rsplit("/", 1)[0] if "/" in key else ""
    return (FIRST_PARTY.index(prefix) if prefix in FIRST_PARTY else len(FIRST_PARTY), len(key), key)


def main():
    if len(sys.argv) > 1:
        table = json.load(open(sys.argv[1]))
    else:
        table = json.load(urllib.request.urlopen(URL, timeout=60))
    best = {}
    for key, e in table.items():
        if not isinstance(e, dict) or e.get("mode") not in ("chat", "responses"):
            continue
        if not e.get("input_cost_per_token") or not e.get("output_cost_per_token"):
            continue
        mid = normalize(key)
        if mid not in best or rank(key) < rank(best[mid][0]):
            best[mid] = (key, e)
    per_m = lambda v: None if v is None else round(v * 1e6, 6)
    out = {}
    for mid, (key, e) in sorted(best.items()):
        out[mid] = [per_m(e["input_cost_per_token"]), per_m(e["output_cost_per_token"]), per_m(e.get("cache_read_input_token_cost")),
                    per_m(e.get("cache_creation_input_token_cost")), per_m(e.get("cache_creation_input_token_cost_above_1hr"))]
    body = json.dumps(out, separators=(",", ":"))
    assert '"#' not in body
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "Sources", "TachCore", "PriceData.swift")
    with open(path, "w") as f:
        f.write("// Generated by scripts/update-prices.py from LiteLLM's price table (MIT). Do not edit by hand.\n")
        f.write("// model id: [input, output, cache read, cache write 5 min, cache write 1 h], US dollars per million tokens.\n")
        f.write("enum PriceData {\n    static let json = #\"\"\"\n" + body + "\n\"\"\"#\n}\n")
    print(f"{len(out)} models written to {os.path.normpath(path)}")


if __name__ == "__main__":
    main()
